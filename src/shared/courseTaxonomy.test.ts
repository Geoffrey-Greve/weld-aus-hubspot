import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import {
  COURSE_CATEGORY_BUCKETS,
  COURSE_CATEGORY_FALLBACK_SLUG,
  bucketForCategory,
  bucketLabel,
  normaliseCategoryKey,
  resolveBucketFromParam,
} from './courseTaxonomy'

interface HubDbColumn {
  name: string
  options?: Array<{ name: string }>
}

function hubdbCategoryOptions(): string[] {
  const schema = JSON.parse(
    readFileSync(resolve(__dirname, '../../hubdb/courses.json'), 'utf8')
  ) as { columns: HubDbColumn[] }
  const column = schema.columns.find((c) => c.name === 'category')
  if (!column?.options) throw new Error('hubdb/courses.json has no `category` SELECT options')
  return column.options.map((o) => o.name)
}

describe('course taxonomy', () => {
  it('maps every HubDB category option to a bucket', () => {
    const unmapped = hubdbCategoryOptions().filter(
      (option) => bucketForCategory(option) === COURSE_CATEGORY_FALLBACK_SLUG
    )
    expect(unmapped, `unmapped HubDB category options: ${unmapped.join(', ')}`).toEqual([])
  })

  it('gives every bucket at least one HubDB value', () => {
    for (const bucket of COURSE_CATEGORY_BUCKETS) {
      expect(bucket.values.length, `bucket "${bucket.slug}" has no HubDB values`).toBeGreaterThan(0)
    }
  })

  it('claims each HubDB value for exactly one bucket', () => {
    const seen = new Map<string, string>()
    for (const bucket of COURSE_CATEGORY_BUCKETS) {
      for (const value of bucket.values) {
        expect(seen.has(value), `"${value}" is claimed twice`).toBe(false)
        seen.set(value, bucket.slug)
      }
    }
  })

  it('normalises spaces, dashes, underscores and case to one key', () => {
    expect(normaliseCategoryKey('Welding Inspection')).toBe('welding-inspection')
    expect(normaliseCategoryKey('welding_inspection')).toBe('welding-inspection')
    expect(normaliseCategoryKey('  WELDING-INSPECTION  ')).toBe('welding-inspection')
  })

  it('resolves the legacy link vocabulary still generated by certification.html', () => {
    // theme/templates/pages/certification.html builds /courses?category=<slug>
    expect(resolveBucketFromParam('inspector')).toBe('welding-inspection')
    expect(resolveBucketFromParam('inspection')).toBe('welding-inspection')
    expect(resolveBucketFromParam('supervision')).toBe('welding-supervision')
    expect(resolveBucketFromParam('certification')).toBe('welding-coordination')
    // The legacy catch-all bucket from training-course-cards.html
    expect(resolveBucketFromParam('appreciation')).toBe('short-courses')
    // Old featured-courses editor field values
    expect(resolveBucketFromParam('welding_inspection')).toBe('welding-inspection')
    expect(resolveBucketFromParam('welder_certification')).toBe('welding-coordination')
  })

  it('resolves raw HubDB values passed straight through the URL', () => {
    expect(resolveBucketFromParam('Robotic Welding')).toBe('short-courses')
    expect(resolveBucketFromParam('Engineering')).toBe('welding-coordination')
  })

  it('returns an empty string for values that name no bucket', () => {
    // Callers fall back to their configured default rather than showing nothing.
    expect(resolveBucketFromParam('')).toBe('')
    expect(resolveBucketFromParam(null)).toBe('')
    expect(resolveBucketFromParam('all')).toBe('')
    expect(resolveBucketFromParam('any')).toBe('')
    expect(resolveBucketFromParam('not-a-category')).toBe('')
  })

  it('falls back rather than throwing on an unknown category value', () => {
    expect(bucketForCategory('Underwater Basket Weaving')).toBe(COURSE_CATEGORY_FALLBACK_SLUG)
    expect(bucketForCategory(undefined)).toBe(COURSE_CATEGORY_FALLBACK_SLUG)
    expect(bucketLabel(COURSE_CATEGORY_FALLBACK_SLUG)).toBe('Other')
  })

  it('labels each bucket with the client-facing division name', () => {
    expect(COURSE_CATEGORY_BUCKETS.map((b) => b.label)).toEqual([
      'Welding Inspection',
      'Welding Supervision',
      'Welding Coordination',
      'Short Courses',
    ])
  })
})
