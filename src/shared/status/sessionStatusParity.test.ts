/**
 * Ref 74c drift guard — the HubL half of the session-status vocabulary.
 *
 * Session status is resolved twice: in TypeScript (`sessionStatus.ts`, for the React
 * islands) and in HubL (`theme/templates/partials/session-status.html`, for the
 * server-rendered card partials). The HubL file is GENERATED from the TypeScript, so they
 * cannot drift by hand — but the generator can be dropped from the build, the partial can
 * be committed stale, and a card partial can stop calling the macros and go back to its own
 * `{% if status_name == 'Sold Out' %}` ladder. That is exactly how the two ladders this
 * replaced came to disagree, one showing a raw HubDB option name and the other a
 * hand-written label, neither knowing what to do with a status nobody had told it about.
 *
 * HubL cannot be executed here, so this asserts the generated file says what the TypeScript
 * says, and that both card partials consume it.
 */
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { HUBDB_STATUS_ALIASES, SESSION_STATUSES, statusPresentation } from './sessionStatus'

const THEME = resolve(__dirname, '../../../theme')
const read = (rel: string) => readFileSync(resolve(THEME, rel), 'utf8')

const MACROS = read('templates/partials/session-status.html')
const CARD_PARTIAL = read('templates/partials/training-course-cards.html')
const COMPACT_MODULE = read('modules/course-timetable-compact.module/module.html')
const DIRECTORY_MODULE = read('modules/featured-courses.module/module.html')

describe('the generated HubL macros match the TypeScript', () => {
  it('is generated, and says so', () => {
    expect(MACROS).toContain('GENERATED by scripts/build.ts')
    expect(MACROS).toContain('src/shared/status/sessionStatus.ts')
  })

  it('maps every HubDB spelling the TypeScript maps', () => {
    for (const alias of Object.keys(HUBDB_STATUS_ALIASES)) {
      expect(MACROS).toContain(`'${alias}'`)
    }
  })

  it('carries every status, with the same slug and the same sentence', () => {
    for (const status of SESSION_STATUSES) {
      const { slug, label } = statusPresentation(status)
      expect(MACROS).toContain(slug)
      expect(MACROS).toContain(label)
    }
  })

  it('answers "off sale" for every non-available alias, in one self-contained macro', () => {
    const macro = MACROS.match(/{% macro is_off_sale\(raw\) %}(.*?){% endmacro %}/)
    expect(macro).not.toBeNull()
    // Self-contained: it must not call another macro, because callers use it from places
    // where a nested call is not something HubL is relied on for.
    expect(macro![1]).not.toMatch(/status_(of|slug|label|is_bookable)\(/)
    for (const [alias, status] of Object.entries(HUBDB_STATUS_ALIASES)) {
      if (!statusPresentation(status).bookable) expect(macro![1]).toContain(`'${alias}'`)
    }
  })

  it('answers "bookable" for available and nothing else', () => {
    // The macro is a string, so the partials compare against "true". A status missing from
    // its branch list would fall through the {% else %} and read as bookable.
    for (const status of SESSION_STATUSES.filter((s) => s !== 'available')) {
      expect(MACROS).toContain(`_s == '${status}' %}false`)
    }
  })
})

describe('the events surfaces honour the row status (Ref 74c Phase 3)', () => {
  const EVENTS_PAGE = read('templates/pages/events.html')
  const EVENT_DETAIL = read('templates/pages/event-detail.html')
  const CHECKOUT_TUNNEL = read('modules/checkout-tunnel.module/module.html')
  const EVENTS_LISTING = read('modules/events-listing.module/module.html')

  for (const [name, source] of [
    ['events.html', EVENTS_PAGE],
    ['event-detail.html', EVENT_DETAIL],
  ] as Array<[string, string]>) {
    it(`${name} resolves status through the shared macros`, () => {
      expect(source).toContain('session-status.html')
      expect(source).toContain('wa_status.status_of(')
      expect(source).toContain('_status_bookable')
    })

    it(`${name} gates the Event Engine section on bookability`, () => {
      expect(source).toContain('_use_engine and _engine_allowed and _status_bookable')
    })

    it(`${name} lets cancelled/closed win over the members-only upsell`, () => {
      // Branch ORDER is the whole test. "Explore membership" on an event nobody can book
      // reads as a bypass that does not exist, and it sits in the same ladder.
      const closedBranch = source.indexOf('{% if not _status_bookable %}')
      const membershipBranch = source.indexOf("'Explore membership'")
      expect(closedBranch).toBeGreaterThan(-1)
      expect(membershipBranch).toBeGreaterThan(-1)
      expect(closedBranch).toBeLessThan(membershipBranch)
    })

    it(`${name} passes the row status to the availability badge`, () => {
      expect(source).toContain('data-hubdb-status=')
    })
  }

  it('the checkout tunnel no longer hardcodes an event as available', () => {
    // The booking path. Hardcoded 'available' here meant a closed event stayed bookable to
    // anyone holding a /checkout/?event_id= link, whatever every listing said.
    expect(CHECKOUT_TUNNEL).not.toContain("'status':            'available',")
    expect(CHECKOUT_TUNNEL).toContain('event_row.status.name')
    // …and it must still default, or event checkout breaks the moment this ships ahead of
    // the column.
    expect(CHECKOUT_TUNNEL).toContain("if event_row.status else 'available'")
  })

  it('the events listing serialises status in BOTH loops and on the badge', () => {
    // Upcoming and past are two separate loops; one without the other is how they drift.
    expect(EVENTS_LISTING.match(/'status':\s+row\.status\.name/g) ?? []).toHaveLength(2)
    expect(EVENTS_LISTING).toContain('data-hubdb-status=')
  })
})

describe('the card partials use the shared macros', () => {
  const surfaces: Array<[string, string]> = [
    ['training-course-cards.html', CARD_PARTIAL],
    ['course-timetable-compact.module', COMPACT_MODULE],
    // The /courses directory card. Missed by the first pass of Ref 74c, so a Closed row
    // rendered as an ordinary card with "Register now".
    ['featured-courses.module', DIRECTORY_MODULE],
  ]

  for (const [name, source] of surfaces) {
    it(`${name} imports and calls them`, () => {
      expect(source).toContain('session-status.html')
      expect(source).toContain('wa_status.status_of(')
      expect(source).toContain('wa_status.status_slug(')
      expect(source).toContain('wa_status.status_label(')
      expect(source).toContain('wa_status.status_is_bookable(')
    })

    it(`${name} gates its Register CTA on bookability, not on one status name`, () => {
      // The defect this guards: `{% if status_name == 'Sold Out' %}` suppressed the CTA for
      // exactly one status, so a Cancelled row - and later a Closed one - was handed a
      // working Register button.
      expect(source).toContain('not status_bookable')
      expect(source).not.toContain("status_name == 'Sold Out'")
      expect(source).not.toContain("status_name == 'Cancelled'")
      expect(source).not.toContain("status_name != 'Available'")
    })
  }
})
