interface CourseCategoryBucketConfig {
  slug: string
  label: string
  url: string
  hubdbValues: string[]
  aliases?: string[]
}

interface CourseCategoryConfig {
  fallback: { slug: string; label: string }
  buckets: CourseCategoryBucketConfig[]
}

/** Lowercase, non-alphanumerics collapsed to single dashes. */
function slugifyCategory(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function hublList(values: string[]): string {
  return `[${values.map((v) => `'${v.replace(/'/g, "\\'")}'`).join(', ')}]`
}

/**
 * Generate the course category taxonomy into the two places that consume it:
 * a HubL macro partial (for the server-rendered course directories) and a
 * TypeScript module (for the React islands). config/course-categories.json is
 * the single source of truth - see its `_comment` block.
 *
 * The vanilla JS inside featured-courses.module does NOT get a third copy: its
 * host HubL emits taxonomy_json("") into a data attribute which the script reads.
 */
function buildCourseTaxonomy(): void {
  if (!existsSync(COURSE_CATEGORIES_JSON)) return

  const config = JSON.parse(
    readFileSync(COURSE_CATEGORIES_JSON, 'utf8')
  ) as CourseCategoryConfig
  if (!Array.isArray(config.buckets) || config.buckets.length === 0) {
    throw new Error('config/course-categories.json must define a non-empty `buckets` array')
  }

  const fallbackSlug = config.fallback.slug
  const fallbackLabel = config.fallback.label

  // Every key that should resolve to a bucket: the slug, the label, each HubDB
  // option name, and each hand-written alias - all slugified to one form so the
  // lookup is insensitive to spaces, dashes and underscores.
  const keysBySlug = new Map<string, string[]>()
  const claimedBy = new Map<string, string>()

  for (const bucket of config.buckets) {
    const keys = new Set<string>()
    for (const raw of [
      bucket.slug,
      bucket.label,
      ...bucket.hubdbValues,
      ...(bucket.aliases ?? []),
    ]) {
      const key = slugifyCategory(raw)
      if (!key) continue
      const owner = claimedBy.get(key)
      if (owner && owner !== bucket.slug) {
        throw new Error(
          `config/course-categories.json: "${key}" is claimed by both "${owner}" and "${bucket.slug}"`
        )
      }
      claimedBy.set(key, bucket.slug)
      keys.add(key)
    }
    keysBySlug.set(bucket.slug, [...keys].sort())
  }

  // ---- HubL macro partial -------------------------------------------------
  const slugsCsv = config.buckets.map((b) => b.slug).join(',')
  const branch = (
    macroArg: string,
    cases: Array<{ test: string; output: string }>,
    fallback: string
  ): string =>
    cases
      .map(({ test, output }, i) => `{% ${i === 0 ? 'if' : 'elif'} ${macroArg} ${test} %}${output}`)
      .join('') + `{% else %}${fallback}{% endif %}`

  const hubl = [
    // Same annotation as the other partials - keeps HubSpot from treating this
    // macro file as a standalone template.
    '<!--',
    '  templateType: none',
    '-->',
    '{#',
    '  course-taxonomy.html',
    '',
    '  GENERATED by scripts/build.ts from config/course-categories.json.',
    '  Do not edit directly - edit the JSON and run `pnpm build`.',
    '',
    "  The client's training divisions are a display grouping over the HubDB",
    '  `courses.category` SELECT options. HubDB values are unchanged.',
    '',
    '  Usage from a module or template:',
    '    {% import "../../templates/partials/course-taxonomy.html" as wa_tax %}',
    '    {% set _bucket = wa_tax.bucket_slug(row.category.name)|trim %}',
    '    {% set _label  = wa_tax.bucket_label(_bucket)|trim %}',
    '    {% set _slugs  = wa_tax.slugs_csv("")|trim|split(",") %}',
    '',
    '  Note: slugs_csv / taxonomy_json take a dummy arg (pass ""). HubL rejects',
    '  zero-arg macro calls on import namespaces (SizeLimitingPyMap:',
    '  "Cannot find method … with 0 parameters").',
    '#}',
    '',
    '{# Map a raw HubDB category value (or any alias/slug) to a bucket slug. #}',
    `{% macro bucket_slug(raw) %}{% set _k = raw|default('', true)|string|lower|trim|replace('_', '-')|replace(' ', '-') %}${branch(
      '_k in',
      config.buckets.map((b) => ({
        test: hublList(keysBySlug.get(b.slug) ?? []),
        output: b.slug,
      })),
      fallbackSlug
    )}{% endmacro %}`,
    '',
    '{# Display label for a bucket slug. #}',
    `{% macro bucket_label(slug) %}{% set _s = slug|default('', true)|string|lower|trim %}${branch(
      '_s ==',
      config.buckets.map((b) => ({ test: `'${b.slug}'`, output: b.label })),
      fallbackLabel
    )}{% endmacro %}`,
    '',
    '{# Landing page URL for a bucket slug. #}',
    `{% macro bucket_url(slug) %}{% set _s = slug|default('', true)|string|lower|trim %}${branch(
      '_s ==',
      config.buckets.map((b) => ({ test: `'${b.slug}'`, output: b.url })),
      '/training/'
    )}{% endmacro %}`,
    '',
    '{# Comma-separated HubDB category option names, for `category__in=` queries. #}',
    `{% macro bucket_values_csv(slug) %}{% set _s = slug|default('', true)|string|lower|trim %}${branch(
      '_s ==',
      config.buckets.map((b) => ({
        test: `'${b.slug}'`,
        output: b.hubdbValues.join(','),
      })),
      ''
    )}{% endmacro %}`,
    '',
    // Dummy `_` arg required: HubL cannot call wa_tax.slugs_csv() (0 params)
    // on an import namespace - SizeLimitingPyMap method lookup fails.
    '{# All bucket slugs in display order. Pass "" for the unused arg. #}',
    `{% macro slugs_csv(_) %}${slugsCsv}{% endmacro %}`,
    '',
    '{# Full taxonomy as JSON, for injection into a data attribute. Pass "" for the unused arg. #}',
    `{% macro taxonomy_json(_) %}${JSON.stringify({
      fallback: fallbackSlug,
      buckets: config.buckets.map((b) => ({
        slug: b.slug,
        label: b.label,
        url: b.url,
        values: b.hubdbValues,
        keys: keysBySlug.get(b.slug) ?? [],
      })),
    })}{% endmacro %}`,
    '',
  ].join('\n')

  writeFileSync(COURSE_TAXONOMY_HUBL, hubl, 'utf8')

  // ---- TypeScript module --------------------------------------------------
  const ts = `/**
 * Course category taxonomy.
 *
 * GENERATED by scripts/build.ts from config/course-categories.json.
 * Do not edit directly - edit the JSON and run \`pnpm build\`.
 *
 * The client's training divisions are a display grouping over the HubDB
 * \`courses.category\` SELECT options. HubDB values are unchanged.
 */

export interface CourseCategoryBucket {
  slug: string
  label: string
  url: string
  /** HubDB \`category\` option names that fall into this bucket. */
  values: string[]
  /** Every slugified key that resolves here: slug, label, values and aliases. */
  keys: string[]
}

export const COURSE_CATEGORY_FALLBACK_SLUG = ${JSON.stringify(fallbackSlug)}
export const COURSE_CATEGORY_FALLBACK_LABEL = ${JSON.stringify(fallbackLabel)}

export const COURSE_CATEGORY_BUCKETS: CourseCategoryBucket[] = ${JSON.stringify(
    config.buckets.map((b) => ({
      slug: b.slug,
      label: b.label,
      url: b.url,
      values: b.hubdbValues,
      keys: keysBySlug.get(b.slug) ?? [],
    })),
    null,
    2
  )}

const KEY_TO_SLUG: Record<string, string> = {}
for (const bucket of COURSE_CATEGORY_BUCKETS) {
  for (const key of bucket.keys) KEY_TO_SLUG[key] = bucket.slug
}

/** Lowercase, non-alphanumerics collapsed to single dashes. */
export function normaliseCategoryKey(value: string | null | undefined): string {
  return (value ?? '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+\$/g, '')
}

/** Map a raw HubDB category value to a bucket slug, or the fallback slug. */
export function bucketForCategory(raw: string | null | undefined): string {
  return KEY_TO_SLUG[normaliseCategoryKey(raw)] ?? COURSE_CATEGORY_FALLBACK_SLUG
}

/**
 * Resolve a \`?category=\` URL param to a bucket slug. Returns '' when the value
 * does not name a bucket, so callers can fall back to their configured default
 * rather than filtering everything away.
 */
export function resolveBucketFromParam(param: string | null | undefined): string {
  const key = normaliseCategoryKey(param)
  if (!key || key === 'all' || key === 'any') return ''
  return KEY_TO_SLUG[key] ?? ''
}

/** Display label for a bucket slug. */
export function bucketLabel(slug: string): string {
  return (
    COURSE_CATEGORY_BUCKETS.find((b) => b.slug === slug)?.label ??
    COURSE_CATEGORY_FALLBACK_LABEL
  )
}
`

  writeFileSync(COURSE_TAXONOMY_TS, ts, 'utf8')
  console.log('[build] Generated course taxonomy from config/course-categories.json')
}

