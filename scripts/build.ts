  const raw = readFileSync(HEADER_MENU_JSON, 'utf8')
  const items = JSON.parse(raw) as HeaderMenuItem[]
  if (!Array.isArray(items)) {
    throw new Error('config/header-menu.json must contain an array of menu items')
  }

