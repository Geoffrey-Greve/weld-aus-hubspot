function hasAnyEntry(): boolean {
  if (!existsSync(MODULES_DIR)) return false
  for (const name of readdirSync(MODULES_DIR)) {
    const dir = join(MODULES_DIR, name)
    if (!statSync(dir).isDirectory()) continue
    if (existsSync(join(dir, 'index.tsx'))) return true
  }
  return false
}

/**
 * Build one self-contained HubSpot bundle per React island and patch its host
 * module.html (and any template hosts) with a STABLE, un-hashed `<script>`/`<link>`
 * tag. This is the sole patcher of module bundle tags - see buildStandaloneEntry.
 */
async function buildStandaloneEntry(moduleName: string): Promise<void> {
  const entryPath = join(MODULES_DIR, moduleName, 'index.tsx')
  const moduleHtmlPath = join(THEME_MODULES_DIR, `${moduleName}.module`, 'module.html')
  if (!existsSync(entryPath) || !existsSync(moduleHtmlPath)) return

  const buildResult = await build({
    configFile: false,
    plugins: [],
    resolve: {
      alias: {
        '@shared': resolve(ROOT, 'src/shared'),
        '@modules': resolve(ROOT, 'src/modules'),
        '@styles': resolve(ROOT, 'src/styles'),
      },
    },
    build: {
      outDir: OUT_DIR,
      emptyOutDir: false,
      sourcemap: true,
      rollupOptions: {
        input: entryPath,
        output: {
          inlineDynamicImports: true,
          // Stable (un-hashed) filenames. HubSpot appends its own content-based
          // cache-buster to get_asset_url() output, so a stable name still busts
          // caches on upload - while keeping the committed module.html free of
          // rotating hashes (no more per-build churn / cross-branch conflicts).
          entryFileNames: `${moduleName}.standalone.js`,
          assetFileNames: `assets/${moduleName}.standalone[extname]`,
        },
      },
    },
    esbuild: {
      jsx: 'automatic',
    },
  })

  // Vite 6 types `build()` as RollupOutput | RollupOutput[] | RollupWatcher.
  // We never enable watch mode here, so reject a watcher and narrow to outputs.
  if (!Array.isArray(buildResult) && !('output' in buildResult)) {
    throw new Error(`Standalone build returned a watcher for ${moduleName}`)
  }
  const outputs = Array.isArray(buildResult)
    ? buildResult.flatMap((result) => result.output)
    : buildResult.output
  const jsFile = outputs.find((output) => output.type === 'chunk' && output.isEntry)?.fileName
  const cssFile = outputs.find(
    (output) => output.type === 'asset' && output.fileName.endsWith('.css')
  )?.fileName
  if (!jsFile) {
    throw new Error(`Standalone build did not produce an entry chunk for ${moduleName}`)
  }
  const cssTag = cssFile
    ? `<link rel="stylesheet" href="{{ get_asset_url('../../assets/js/${cssFile}') }}">\n`
    : ''
  const standaloneTag =
    `${cssTag}<script type="module" src="{{ get_asset_url('../../assets/js/${jsFile}') }}"></script>`
  // Match the previously-written tag block, whether it used the old hashed name
  // (`<name>.standalone.<hash>.js` / legacy main-build `<name>.<hash>.js`) or the
  // new stable name (`<name>.standalone.js`). The hash segment is optional so a
  // rebuild is idempotent and the first build after this change migrates cleanly.
  const escapedName = escapeRegExp(moduleName)
  const existingTagPattern = new RegExp(
    `(?:<link rel="stylesheet" href="{{ get_asset_url\\('(?:\\.\\.\/){1,2}assets\/js\/assets\/[^']+\\.css'\\) }}">\\r?\\n)*` +
      `<script type="module" src="{{ get_asset_url\\('(?:\\.\\.\/){1,2}assets\/js\/${escapedName}(?:\\.standalone)?(?:\\.[A-Za-z0-9_-]+)?\\.js'\\) }}"></script>`
  )
  const placeholder = `{# @bundle: ${moduleName} #}`
  const html = readFileSync(moduleHtmlPath, 'utf8')
  let patchedHtml: string
  if (html.includes(placeholder)) {
    patchedHtml = html.replace(placeholder, standaloneTag)
  } else if (existingTagPattern.test(html)) {
    patchedHtml = html.replace(existingTagPattern, standaloneTag)
  } else {
    throw new Error(`Could not patch standalone bundle tag for ${moduleName}`)
  }
  writeFileSync(moduleHtmlPath, patchedHtml, 'utf8')

  for (const templateName of STANDALONE_TEMPLATE_HOSTS[moduleName] ?? []) {
    const templatePath = join(ROOT, 'theme', 'templates', 'pages', templateName)
    if (!existsSync(templatePath)) continue
    const templateHtml = readFileSync(templatePath, 'utf8')
    const assetPattern = new RegExp(
      `\\.\\.\\/\\.\\.\\/assets\\/js\\/${escapedName}\\.standalone(?:\\.[A-Za-z0-9_-]+)?\\.js`,
      'g'
    )
    writeFileSync(
      templatePath,
      templateHtml.replace(assetPattern, `../../assets/js/${jsFile}`),
      'utf8'
    )
  }

  console.log(`[build] Built standalone HubSpot bundle for ${moduleName}`)
}

/**
 * Some modules render server-side in HubL (no client React island) but still
 * reuse a component's Vite-built CSS via a direct <link>. Vite emits that CSS
 * with a rotating content hash; committing the hashed href churns the file every
 * build and 404s the moment the hash moves. For these CSS-only modules we copy
 * the built CSS to a STABLE filename (assets/<name>.css) and rewrite the host
 * module.html <link> to it - no runtime/behaviour change, just a stable, always-
 * resolvable reference (HubSpot cache-busts get_asset_url output on upload).
 */
const CSS_ONLY_MODULES = ['events-listing'] as const

function stabiliseCssOnlyModules(): void {
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8')) as Record<
    string,
    { css?: string[] }
  >
  for (const moduleName of CSS_ONLY_MODULES) {
    const entry = manifest[`src/modules/${moduleName}/index.tsx`]
    const hashedCss = entry?.css?.find((f) => f.endsWith('.css'))
    if (!hashedCss) continue
    const stableRel = `assets/${moduleName}.css`
    copyFileSync(join(OUT_DIR, hashedCss), join(OUT_DIR, stableRel))

    const moduleHtmlPath = join(THEME_MODULES_DIR, `${moduleName}.module`, 'module.html')
    if (!existsSync(moduleHtmlPath)) continue
    const escapedName = escapeRegExp(moduleName)
    const linkPattern = new RegExp(
      `(<link rel="stylesheet" href="{{ get_asset_url\\('(?:\\.\\.\/){1,2}assets\/js\/assets\/)${escapedName}(?:\\.[A-Za-z0-9_-]+)?(\\.css'\\) }}">)`
    )
    const html = readFileSync(moduleHtmlPath, 'utf8')
    if (!linkPattern.test(html)) {
      console.warn(`[build] No CSS <link> to stabilise for ${moduleName} - skipping.`)
      continue
    }
    writeFileSync(moduleHtmlPath, html.replace(linkPattern, `$1${moduleName}$2`), 'utf8')
    console.log(`[build] Stabilised CSS reference for ${moduleName} → ${stableRel}`)
  }
}

/**
 * Generates the HubL half of the session-status vocabulary (Ref 74c).
 *
 * `src/shared/status/sessionStatus.ts` is the single source: the React islands import it,
 * and this writes the same table out as HubL macros for the server-rendered card partials.
 * Before this, `training-course-cards.html` and `course-timetable-compact.module` each
 * carried their own `{% if status_name == 'Sold Out' %}` ladder, and they had already
 * drifted - one showed the raw HubDB option name, the other a hand-written label, and
 * neither knew what to do with a status it had not been told about. Adding "Closed" to two
 * ladders and a React file is exactly the change that leaves one of them behind.
 *
 * Same pattern (and the same warning banner) as buildCourseTaxonomy above.
 */
function buildSessionStatusMacros(): void {
  const hubl = (s: string) => s.replace(/'/g, "\\'")

  // Normalised alias -> status, grouped so each status gets one `in [...]` branch.
  const aliasesByStatus = new Map<SessionStatus, string[]>()
  for (const [alias, status] of Object.entries(HUBDB_STATUS_ALIASES)) {
    aliasesByStatus.set(status, [...(aliasesByStatus.get(status) ?? []), alias].sort())
  }

  // Every alias that resolves to anything but `available` - which today is all of them.
  const offSaleAliases = Object.entries(HUBDB_STATUS_ALIASES)
    .filter(([, status]) => !statusPresentation(status).bookable)
    .map(([alias]) => alias)
    .sort()

  const normalise = `{% set _k = raw|default('', true)|string|lower|trim|replace(' ', '_')|replace('-', '_') %}`
  const statusBranches = [...aliasesByStatus.entries()]
    .map(
      ([status, aliases], i) =>
        `{% ${i === 0 ? 'if' : 'elif'} _k in [${aliases.map((a) => `'${hubl(a)}'`).join(', ')}] %}${status}`
    )
    .join('')

  const branchOn = (pick: (status: SessionStatus) => string) =>
    SESSION_STATUSES.filter((s) => s !== 'available')
      .map(
        (status, i) =>
          `{% ${i === 0 ? 'if' : 'elif'} _s == '${status}' %}${pick(status)}`
      )
      .join('')

  const lines = [
    '<!--',
    '  templateType: none',
    '-->',
    '{#',
    '  session-status.html',
    '',
    '  GENERATED by scripts/build.ts from src/shared/status/sessionStatus.ts.',
    '  Do not edit directly - edit the TypeScript and run `pnpm build`.',
    '',
    '  One vocabulary for "can this session be booked, and if not, why not", shared by the',
    '  HubL card partials and the React islands. Ref 74c.',
    '',
    '  Usage from a module or template:',
    '    {% import "../../templates/partials/session-status.html" as wa_status %}',
    '    {% set _status = wa_status.status_of(row.status.name)|trim %}',
    '    {% set _slug   = wa_status.status_slug(_status)|trim %}',
    '    {% set _label  = wa_status.status_label(_status)|trim %}',
    '    {% set _open   = wa_status.status_is_bookable(_status)|trim == "true" %}',
    '    {% if wa_status.is_off_sale(row.status.name)|trim %} ... {% endif %}',
    '#}',
    '',
    '{# Raw HubDB status value (any spelling) -> status key. #}',
    `{% macro status_of(raw) %}${normalise}${statusBranches}{% else %}available{% endif %}{% endmacro %}`,
    '',
    '{# Status key -> CSS slug. #}',
    `{% macro status_slug(status) %}{% set _s = status|default('', true)|string|lower|trim %}${branchOn((s) => statusPresentation(s).slug)}{% else %}available{% endif %}{% endmacro %}`,
    '',
    '{# Status key -> the sentence a buyer is shown. #}',
    `{% macro status_label(status) %}{% set _s = status|default('', true)|string|lower|trim %}${branchOn((s) => hubl(statusPresentation(s).label))}{% else %}${hubl(statusPresentation('available').label)}{% endif %}{% endmacro %}`,
    '',
    '{# "true" only for a session that may be booked. Compare against the string. #}',
    `{% macro status_is_bookable(status) %}{% set _s = status|default('', true)|string|lower|trim %}${branchOn(() => 'false')}{% else %}true{% endif %}{% endmacro %}`,
    '',
    '{# Raw HubDB status value -> "true" when it takes the session off sale, else "".',
    '   One call, no nesting: for surfaces that only need the yes/no, and for macro files,',
    '   where a call into another imported namespace is not something to rely on. #}',
    `{% macro is_off_sale(raw) %}${normalise}{% if _k in [${offSaleAliases.map((a) => `'${hubl(a)}'`).join(', ')}] %}true{% endif %}{% endmacro %}`,
    '',
  ]

  writeFileSync(SESSION_STATUS_PARTIAL, `${lines.join('\n')}`, 'utf8')
  console.log(`[build] Generated ${SESSION_STATUS_PARTIAL}`)
}

/**
 * Vanilla (non-React) scripts that need to IMPORT shared TypeScript.
 *
 * `src/vanilla/*.js` is copied verbatim, which is why the events availability badge used to
 * carry its own hand-rolled copy of the availability logic - a copied file cannot import
 * `@shared/…`. These entries are bundled instead, and deliberately as an **IIFE**: all three
 * host templates load the result with a plain `<script src … defer>`, not `type="module"`,
 * so an ESM bundle would be silently dead on every events page.
 *
 * The output keeps the un-hashed name the templates already reference, so nothing in HubL
 * changes. (HubSpot cache-busts `get_asset_url()` on upload, as it does for the standalone
 * module bundles.)
 */
const VANILLA_TS_ENTRIES = [
  { name: 'event-availability', entry: 'src/vanilla/event-availability.entry.ts' },
] as const

async function buildVanillaEntries(): Promise<void> {
  for (const { name, entry } of VANILLA_TS_ENTRIES) {
    const entryPath = resolve(ROOT, entry)
    if (!existsSync(entryPath)) {
      throw new Error(`[build] Vanilla entry missing: ${entry}`)
    }
    await build({
      configFile: false,
      plugins: [],
      resolve: {
        alias: {
          '@shared': resolve(ROOT, 'src/shared'),
          '@modules': resolve(ROOT, 'src/modules'),
          '@styles': resolve(ROOT, 'src/styles'),
        },
      },
      build: {
        outDir: OUT_DIR,
        emptyOutDir: false,
        sourcemap: true,
        lib: {
          entry: entryPath,
          name: 'WAEventAvailability',
          formats: ['iife'],
          fileName: () => `${name}.js`,
        },
      },
    })

    // The templates load this with a classic <script>. An `import`/`export` at top level
    // would throw before a single badge bound, and nothing on the page would say so.
    const built = readFileSync(join(OUT_DIR, `${name}.js`), 'utf8')
    if (/^\s*(import|export)\s/m.test(built)) {
      throw new Error(
        `[build] ${name}.js is not a classic script - the host templates load it without ` +
          `type="module" and it would never run.`
      )
    }
    console.log(`[build] Built vanilla entry ${name} → theme/assets/js/${name}.js (iife)`)
  }
}

