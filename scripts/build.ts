interface HeaderMenuItem {
  label: string
  url?: string
  overviewLabel?: string
  openInNewTab?: boolean
  children?: HeaderMenuItem[]
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function normaliseHref(value?: string): string {
  return value && value.trim() ? value.trim() : '#'
}

const INTERNAL_HOST_MARKERS = [
  'staging-441838610.weldaustralia.com',
  '441838610.hs-sites-ap1.com',
  'weldaustralia.com.au',
]

function isExternalHref(href: string): boolean {
  const hrefKey = href.toLowerCase()
  const isAbsolute = hrefKey.startsWith('http://') || hrefKey.startsWith('https://')
  return isAbsolute && !INTERNAL_HOST_MARKERS.some((marker) => hrefKey.includes(marker))
}

function linkTargetAttrs(item: HeaderMenuItem, href: string): string {
  return item.openInNewTab || isExternalHref(href) ? ' target="_blank" rel="noopener noreferrer"' : ''
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function replaceGeneratedBlock(
  html: string,
  name: 'desktop' | 'mobile',
  content: string
): string {
  const start = `{# @generated-header-menu:${name}:start #}`
  const end = `{# @generated-header-menu:${name}:end #}`
  const pattern = new RegExp(`${escapeRegExp(start)}[\\s\\S]*?${escapeRegExp(end)}`)

  if (!pattern.test(html)) {
    throw new Error(`Missing generated header menu markers for ${name} in theme/modules/header.module/module.html`)
  }

  return html.replace(pattern, `${start}\n${content}\n${end}`)
}

